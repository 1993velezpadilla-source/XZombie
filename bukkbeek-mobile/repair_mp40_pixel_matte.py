#!/usr/bin/env python3
"""MP40Pixel V4: repair black-matte damage without altering original RGB.

The legacy transparent sprites were generated by removing nearly-black
background pixels. Unfortunately, that also removed the black MP40 receiver,
magazine, barrel and iron sight. Enlarging the PNG can never restore them.

Repair ONLY the alpha channel within a locally closed firearm silhouette.
Keep original source RGB unchanged so dark detail reappears when available.
Operate PER ATLAS CELL to avoid accidentally bridging two different poses.
"""
from __future__ import annotations
from pathlib import Path
from PIL import Image, ImageOps, ImageFilter, ImageDraw, ImageChops
import json
import sys

FRAMES = (
    "idle_hip_01", "ads_idle", "fire_hip_01", "ads_fire_01", "sprint_01",
    "reload_01", "reload_02", "reload_03", "reload_04",
)

def repair_alpha(source: Image.Image, *, radius: int) -> tuple[Image.Image, dict]:
    im = source.convert("RGBA")
    w, h = im.size
    a = im.getchannel("A")
    mask = a.point(lambda x: 255 if x > 96 else 0)
    pad = radius + 6
    padded = ImageOps.expand(mask, border=pad, fill=0)
    closed = padded.filter(ImageFilter.MaxFilter(radius * 2 + 1))
    closed = closed.filter(ImageFilter.MinFilter(radius * 2 + 1))
    # The outside is connected to the canvas border. Only enclosed dark
    # holes INSIDE the MP40 silhouette become opaque; not the world behind it.
    ImageDraw.floodfill(closed, (0, 0), 128, thresh=0)
    solid = closed.point(lambda x: 0 if x == 128 else 255).crop(
        (pad, pad, pad + w, pad + h))
    repaired_alpha = ImageChops.lighter(solid, a)
    recovered = ImageChops.subtract(repaired_alpha, a)
    before = sum(1 for v in a.getdata() if v > 96)
    after = sum(1 for v in repaired_alpha.getdata() if v > 96)
    rgb = im.convert("RGB")
    # How many hidden original dark-metal RGB pixels are actually retained?
    colored = 0
    zero_rgb = 0
    for px, restored in zip(rgb.getdata(), recovered.getdata()):
        if restored > 96:
            if max(px) > 1: colored += 1
            else: zero_rgb += 1
    im.putalpha(repaired_alpha)
    return im, dict(size=[w, h], originally_visible=before, after=after,
        repaired=after - before, hidden_source_rgb_retained=colored,
        hidden_source_rgb_lost=zero_rgb)

def strip_native_ads_sheet_ghosts(image: Image.Image, frame_name: str) -> tuple[Image.Image, int]:
    """Remove real source-sheet debris confirmed on the V5 RGB/alpha artifact.

    The two ADS source cells retain stray patches at x=0..25 and x=446..
    after component filtering (many pixels have alpha BELOW its 48 cutoff).
    Those bands contain *no weapon* in the measured 482/483-pixel frames:
    receiver + both gloves live inside x=32..405, and fire shell x=350..410.
    Erase only alpha, never source RGB, iron sights or cartridge.
    """
    a = image.getchannel("A")
    w, h = a.size
    cut_left, cut_right = 26, 36
    assert w >= 480 and h == 326, "Unrecognized MP40Pixel ADS source frame geometry"
    before = sum(1 for value in a.getdata() if value > 5)
    d = ImageDraw.Draw(a)
    d.rectangle((0, 0, cut_left - 1, h - 1), fill=0)
    d.rectangle((w - cut_right, 0, w - 1, h - 1), fill=0)
    # The original ADS fire cell also contains a detached caption/bar on its
    # final sprite-sheet rows, BELOW the receiver and in between glove cuffs.
    if frame_name == "ads_fire_01":
        d.rectangle((150, 318, 338, h - 1), fill=0)
    after = sum(1 for value in a.getdata() if value > 5)
    image.putalpha(a)
    print(f"MP40_PIXEL_ADS_GHOST_GUARD frame={frame_name} erased_visible_px={before-after}")
    return image, before - after

def repair_atlas(asset: Path) -> dict:
    atlas = Image.open(asset).convert("RGBA")
    assert atlas.width % 3 == 0 and atlas.height % 3 == 0
    cell_w, cell_h = atlas.width // 3, atlas.height // 3
    source = atlas.copy()
    report = {}
    for i, name in enumerate(FRAMES):
        box = (i % 3 * cell_w, i // 3 * cell_h,
               (i % 3 + 1) * cell_w, (i // 3 + 1) * cell_h)
        radius = 2 if cell_w <= 128 else (3 if cell_w < 300 else 5)
        frame, details = repair_alpha(source.crop(box), radius=radius)
        atlas.paste(frame, box[:2])
        report[name] = details
    atlas.save(asset, format="PNG", optimize=True)
    report["source_cell_size"] = [cell_w, cell_h]
    report["source_is_lowres"] = cell_w < 256
    return report

def main(root: Path) -> None:
    root = root.resolve()
    stem = root / "mobile/mp40_pixel"
    atlas_file = stem / "atlas.png"
    assert atlas_file.exists(), "MP40_PIXEL_MATTE_RED atlas absent"
    report = {"atlas": repair_atlas(atlas_file), "frames": {}}
    frame_dir = stem / "frames"
    if frame_dir.exists():
        for name in FRAMES:
            file = frame_dir / (name + ".png")
            if file.exists():
                image, stats = repair_alpha(Image.open(file), radius=5)
                if name in ("ads_idle", "ads_fire_01"):
                    image, erased = strip_native_ads_sheet_ghosts(image, name)
                    stats["source_edge_ghost_pixels_removed"] = erased
                image.save(file, format="PNG", optimize=True)
                report["frames"][name] = stats
    (stem / "matte_repair_report.json").write_text(
        json.dumps(report, indent=2) + "\n")
    repaired = sum(v["repaired"] for v in report["atlas"].values()
        if isinstance(v, dict) and "repaired" in v)
    if repaired == 0:
        print("MP40_PIXEL_MATTE_WARNING: No enclosed alpha holes were recoverable from this PNG; keeping original sprites, never pretending to restore missing details.")
    print("MP40_PIXEL_MATTE_REPAIR_GREEN atlas_recovered_px=", repaired,
        " native_frames=",len(report["frames"]),
        " source_resolution=",report["atlas"]["source_cell_size"],
        " lowres_fallback=", report["atlas"]["source_is_lowres"])
    if report["atlas"]["source_is_lowres"] and not report["frames"]:
        print("MP40_PIXEL_SOURCE_LOWRES_WARNING: silhouette restored, but full-resolution art is absent; do not label visual fidelity as final.")

if __name__ == "__main__":
    assert len(sys.argv) == 2
    main(Path(sys.argv[1]))
